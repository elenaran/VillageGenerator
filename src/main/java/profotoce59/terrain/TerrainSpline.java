    private static int lowerBound(float[] loc, int offset, int n, float v) {
        int start = 0, len = n;
        while (len > 0) {
            int half = len / 2;
            int mid = start + half;
            if (v < loc[offset + mid]) {
                len = half;
            } else {
                start = mid + 1;
                len -= half + 1;
            }
        }
        return start;
    }

    private static float lerpf(float delta, float a, float b) {
        return a + delta * (b - a);
    }

    public static float apply(int root, float[] p) {
        if (KIND[root] == 1) {
            return CONSTANT[root];
        }

        float f = p[COORD[root]];
        int n = N[root];
        int locOffset = LOC[root];
        int derOffset = DER[root];
        int childOffset = CHILD_IDX[root];

        int i = lowerBound(FLOATS, locOffset, n, f) - 1;
        int j = n - 1;

        if (i < 0) {
            return apply(CHILD[childOffset], p) + FLOATS[derOffset] * (f - FLOATS[locOffset]);
        }
        if (i == j) {
            return apply(CHILD[childOffset + j], p) + FLOATS[derOffset + j] * (f - FLOATS[locOffset + j]);
        }

        float g = FLOATS[locOffset + i];
        float h = FLOATS[locOffset + i + 1];
        float k = (f - g) / (h - g);

        int ci = CHILD[childOffset + i];
        int cj = CHILD[childOffset + i + 1];
        float l = apply(ci, p);
        float m = apply(cj, p);
        float d1 = FLOATS[derOffset + i];
        float d2 = FLOATS[derOffset + i + 1];

        float pp = d1 * (h - g) - (m - l);
        float qq = -d2 * (h - g) + (m - l);

        return lerpf(k, l, m) + k * (1.0f - k) * lerpf(k, pp, qq);
    }

    public static float normalizedWeirdness261(double w) {
        double a = Math.abs(w);
        double b = -0.6666666666666666 + a;
        double c = Math.abs(b);
        double d = -0.3333333333333333 + c;
        return (float) (-3.0 * d);
    }

